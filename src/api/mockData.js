// 根据 base64 内容计算多维度哈希值
function computeHashes(imageBase64) {
  const len = imageBase64.length
  let h1 = 0, h2 = 0, h3 = 0, h4 = 0, h5 = 0
  const step = Math.max(1, Math.floor(len / 100))
  for (let i = 0; i < len; i += step) {
    const c = imageBase64.charCodeAt(i)
    h1 = ((h1 << 5) - h1 + c) | 0
    h2 = (h2 * 37 + c) | 0
    h3 = (h3 * 131 + c) | 0
    h4 = (h4 * 53 + (i % 7) * c) | 0
    h5 = (h5 * 17 + len + c) | 0
  }
  return [
    Math.abs(h1) % ocrOpeners.length,
    Math.abs(h2) % ocrBodies.length,
    Math.abs(h3) % ocrBodies.length,
    Math.abs(h4) % ocrEndings.length,
  ]
}

